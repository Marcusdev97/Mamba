export function crmFieldOwnership() {
  return Object.fromEntries(Object.entries(NOTION_CRM_DATABASES).map(([database, definition]) => [
    database,
    Object.fromEntries(Object.entries(definition.properties).map(([property, config]) => [property, config.ownership])),
  ]));
}

export function crmSchemaManifest() {
  return {
    version: NOTION_CRM_SCHEMA_VERSION,
    databases: NOTION_CRM_DATABASES,
    views: NOTION_CRM_VIEWS,
    privacyDenylist: NOTION_CRM_PRIVACY_DENYLIST,
    fieldOwnership: crmFieldOwnership(),
  };
}
